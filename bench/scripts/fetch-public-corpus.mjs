#!/usr/bin/env node
// Fetches the public benchmark corpus into bench/corpora/k8s-docs/.
//
//   node bench/scripts/fetch-public-corpus.mjs
//
// The corpus is NOT vendored into this repo. It is 398 files of someone else's
// CC BY 4.0 documentation; committing it would bloat the repo, stale silently,
// and put us in the business of redistributing it. A script that pins a commit
// gives the same reproducibility without any of that.
//
// Slice: kubernetes/website content/en/docs/concepts + content/en/docs/tasks.
// Chosen because 398 documents is a haystack ~33x the CI fixture, so finding
// the right note has to be earned; ~904k tokens keeps full-context genuinely
// expensive but still runnable (above ~1M it stops being a baseline and becomes
// impossible, removing the ceiling the whole comparison is measured against);
// and Kubernetes has the deepest public source of REAL questions, which is the
// expensive half of a question set.
//
// content/en/docs/reference is MOSTLY excluded, and the exclusion used to be
// total. That was too coarse. Measured at the pinned commit, reference is
// 2.78M tokens, but 81% of it is the autogenerated part the exclusion was
// actually aimed at — kubernetes-api 1.52M, kubectl 416k, config-api 179k,
// setup-tools 132k. Generated docs have a structural regularity that flatters
// any retriever and fail the human-written-prose criterion, so those stay out.
//
// The rest is hand-written prose that concepts and tasks actively depend on:
// 218 of their 399 files link into reference, 812 times. Excluding all of it
// left holes shaped exactly like the questions a benchmark most wants to ask.
// Two were hit while writing question sets: RBAC has no definition anywhere in
// the slice, and service.md delegates traffic-policy mechanics to
// reference/networking. Worse, 24 files opened with a `glossary_definition`
// shortcode whose text Hugo injects from reference/glossary at build time — so
// concepts/configuration/configmap.md never said what a ConfigMap is.
//
// Four subdirectories are therefore included, +58k tokens for ~962k total.
// The ceiling above is the binding constraint on how much more can come in:
// access-authn-authz (112k, where RBAC lives) and labels-annotations-taints
// (29k) would push the corpus to or past 1M and are left out. RBAC is a known,
// documented hole rather than a surprise one.
import { execFileSync } from 'node:child_process';
import { existsSync, rmSync, mkdirSync, cpSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dest = resolve(here, '../corpora/k8s-docs');
const tmp = resolve(here, '../corpora/.k8s-website-checkout');

// Pinned so a re-run reproduces the same corpus. Upstream moves constantly;
// an unpinned fetch would silently change what every published number is
// measured against.
//
// This used to default to `main` and merely RECORD the resulting sha in
// PROVENANCE.md, which documents a corpus rather than pinning one: re-running
// it any time after the first fetch produced different documents under the same
// instructions, and a gold path verified against one commit can vanish in the
// next. The sha below is the commit both the pilot question set and every
// number so far were built against. It is checked out explicitly because
// `git clone --branch` accepts refs but not commit shas — passing one there
// fails outright, which is why "pinned" was never actually wired up.
const REPO = 'https://github.com/kubernetes/website.git';
const PINNED_COMMIT = '680b6f99b8e0e4b63d56a76d2f11be5fa821c878';
const REF = process.env.K8S_DOCS_REF ?? PINNED_COMMIT;
const SLICES = [
  'content/en/docs/concepts',
  'content/en/docs/tasks',
  'content/en/docs/reference/glossary',
  'content/en/docs/reference/networking',
  'content/en/docs/reference/node',
  'content/en/docs/reference/scheduling',
];

if (existsSync(dest)) {
  console.log(`${dest} already exists — delete it to re-fetch.`);
  process.exit(0);
}

rmSync(tmp, { recursive: true, force: true });
mkdirSync(dirname(tmp), { recursive: true });

// Clone the default branch, then fetch and check out REF by name OR sha. The
// two-step exists because `--branch` rejects a commit sha, and the sha is the
// whole point of pinning.
console.log(`cloning ${REPO} @ ${REF} (sparse, blobless)...`);
execFileSync('git', ['clone', '--depth', '1', '--filter=blob:none', '--sparse', REPO, tmp], { stdio: 'inherit' });
execFileSync('git', ['-C', tmp, 'fetch', '--depth', '1', 'origin', REF], { stdio: 'inherit' });
execFileSync('git', ['-C', tmp, 'checkout', '--detach', 'FETCH_HEAD'], { stdio: 'inherit' });
execFileSync('git', ['-C', tmp, 'sparse-checkout', 'set', ...SLICES], { stdio: 'inherit' });

const sha = execFileSync('git', ['-C', tmp, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
// A pinned fetch that silently lands somewhere else is worse than an unpinned
// one, because PROVENANCE.md would then attest to a commit nobody chose.
if (REF === PINNED_COMMIT && sha !== PINNED_COMMIT) {
  throw new Error(`asked for ${PINNED_COMMIT} but checked out ${sha}`);
}

// Laid out by the slice's path BELOW content/en/docs, not by its last segment.
// `slice.split('/').pop()` flattened every slice to a bare directory name, which
// was harmless while the slices were concepts and tasks and collides the moment
// reference subdirectories arrive — reference/node would land as `node/`, a
// sibling of `concepts/` with nothing saying where it came from. Keeping the
// relative path means existing gold paths (`concepts/...`, `tasks/...`) are
// untouched and the new material is self-describing as `reference/...`.
const DOCS_ROOT = 'content/en/docs/';
mkdirSync(dest, { recursive: true });
for (const slice of SLICES) {
  if (!slice.startsWith(DOCS_ROOT)) throw new Error(`slice outside ${DOCS_ROOT}: ${slice}`);
  const rel = slice.slice(DOCS_ROOT.length);
  cpSync(join(tmp, slice), join(dest, rel), { recursive: true });
}

// The provenance travels with the corpus, not just in this script. Anyone who
// finds the directory later can tell what it is, what commit it came from, and
// what the licence obliges them to do.
writeFileSync(join(dest, 'PROVENANCE.md'),
  `# Public benchmark corpus\n\n` +
  `Source: ${REPO}\n` +
  `Ref: ${REF}\n` +
  `Commit: ${sha}\n` +
  `Slices: ${SLICES.join(', ')}\n` +
  `Fetched by: bench/scripts/fetch-public-corpus.mjs\n\n` +
  `## Licence\n\n` +
  `The Kubernetes documentation is licensed CC BY 4.0 by The Kubernetes Authors.\n` +
  `https://creativecommons.org/licenses/by/4.0/\n\n` +
  `It is fetched, not vendored: this directory is gitignored and is not\n` +
  `redistributed as part of N1X Cortex. Any published benchmark result derived\n` +
  `from it must credit The Kubernetes Authors and state the commit above.\n`);

rmSync(tmp, { recursive: true, force: true });
console.log(`\nwrote ${dest} @ ${sha.slice(0, 12)}`);
console.log('Next: author a question set, then measure contamination on the first');
console.log('batch before writing the rest — see bench/README.md, "Public corpus".');
